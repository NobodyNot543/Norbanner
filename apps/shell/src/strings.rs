static CURRENT: AtomicU8 = AtomicU8::new(0);

pub fn set_language(language: Language) {
    use norbanner_shell::system::{UiLanguage, ui_language};
    let resolved = match language {
        Language::System => match ui_language() {
            UiLanguage::Spanish => 1,
            UiLanguage::French => 2,
            UiLanguage::Portuguese => 3,
            _ => 0,
        },
        Language::Es => 1,
        Language::Fr => 2,
        Language::Pt => 3,
        _ => 0,
    };
    CURRENT.store(resolved, Ordering::Relaxed);
}

pub fn text() -> &'static Strings {
    match CURRENT.load(Ordering::Relaxed) {
        1 => &ES,
        2 => &FR,
        3 => &PT,
        _ => &EN,
    }
}
